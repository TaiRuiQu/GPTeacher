const xml = (text: string) =>
  text.replace(
    /[&<>"']/g,
    (character) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' })[character]!,
  );

function board(title: string, rows: string[]) {
  return `\n\n\`\`\`svg\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 900 450"><rect width="900" height="450" fill="#ffffff"/><text x="60" y="78" fill="#71717a" font-size="24" font-family="sans-serif">${xml(title)}</text>${rows.map((row, index) => `<text x="60" y="${160 + index * 80}" fill="${index === 0 ? '#18181b' : '#2563eb'}" font-size="${index === 0 ? 42 : 32}" font-family="sans-serif">${xml(row)}</text>`).join('')}</svg>\n\`\`\``;
}

function exercise(
  id: string,
  question: string,
  answer: string,
  explanation: string,
  skill: string,
  options: string[] = [],
): Exercise {
  return { id, question, answer, explanation, skill, options };
}

function lesson(
  id: string,
  title: string,
  objective: string,
  sections: [string, string][],
  exercises: Exercise[],
  minutes = 8,
): CourseLesson {
  return {
    kind: 'lesson',
    status: 'ready',
    id,
    title,
    objective,
    minutes,
    source: `# ${title}\n\n${objective}\n\n${sections.map(([heading, body]) => `## ${heading}\n\n${body}`).join('\n\n')}`,
    exercises,
    knowledgePoints: [objective],
    techniques: sections.map(([heading]) => heading),
    sources: [],
  };
}

